package com.chrisnewland.jitwatch.mcp;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.List;
import java.util.Map;

import org.junit.jupiter.api.Assumptions;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;

import com.chrisnewland.jitwatch.mcp.answer.Answer;
import com.chrisnewland.jitwatch.mcp.answer.Budget;
import com.chrisnewland.jitwatch.mcp.session.SessionStore;
import com.chrisnewland.jitwatch.mcp.tools.CheckupTool;
import com.chrisnewland.jitwatch.mcp.tools.DeoptsTool;
